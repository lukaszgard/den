// The privilege helper lets den bring the VPN up and down without an admin
// prompt. `den vpn install-helper` installs, as root, a small wrapper plus a
// sudoers rule pinned to it, so den can call it with `sudo -n`.
//
// The wrapper takes a profile slug and nothing else. That is the whole point of
// it: the sudoers rule makes this command run as root without a password, and
// openfortivpn's own options can load code as root (--pppd-plugin) or write to
// any file (--pppd-log), so no argument, path or config the user can edit is
// ever allowed to reach it. Everything comes from the root-owned config
// rendered at install time.
const (
	// HelperPrefix lives under /opt because the whole chain above the wrapper
	// must be root-owned. On macOS /Library and /usr/local are admin-writable,
	// which would let anything running as the user replace the wrapper that
	// sudo then runs as root.
	HelperPrefix = "/opt/den"
	HelperPath   = HelperPrefix + "/libexec/den-vpn"
	SudoersPath  = "/etc/sudoers.d/den-vpn"

	// helperProtocol is printed by `den-vpn check`. den refuses a wrapper that
	// answers with anything else, so an older install is reported rather than
	// driven with arguments it does not understand.
	helperProtocol = "den-vpn 1"
)

// HelperConfPath, HelperLogPath and HelperPidPath locate a profile's files.
func HelperConfPath(slug string) string { return filepath.Join(HelperPrefix, "etc", slug+".conf") }
func HelperLogPath(slug string) string  { return filepath.Join(HelperPrefix, "var", "log", slug+".log") }
func HelperPidPath(slug string) string  { return filepath.Join(HelperPrefix, "var", "run", slug+".pid") }

var slugPattern = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,31}$`)

// Slug derives a profile identifier from a VPN's display name. It is the only
// parameter den passes to the wrapper, and it appears verbatim in the sudoers
// rules, so it is restricted to a shape that cannot be mistaken for a flag, a
// path or a second command.
func Slug(name string) string {
	var b strings.Builder
	prevDash := false
	for _, r := range strings.ToLower(name) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
			prevDash = false
		default:
			if b.Len() > 0 && !prevDash {
				b.WriteByte('-')
				prevDash = true
			}
		}
	}
	slug := strings.Trim(b.String(), "-")
	if len(slug) > 32 {
		slug = strings.Trim(slug[:32], "-")
	}
	return slug
}

// ValidSlug rejects anything Slug would not have produced.
func ValidSlug(slug string) error {
	if !slugPattern.MatchString(slug) {
		return fmt.Errorf("invalid profile name %q: expected 1-32 characters of a-z, 0-9 or '-'", slug)
	}
	return nil
}

// forbiddenKeys are openfortivpn settings that hand root to whoever set them:
// pppd-plugin loads a shared object, pppd-call reads an arbitrary pppd options
// file, and pppd-log writes to any path. den refuses to bake them into a config
// it will run without a password.
var forbiddenKeys = map[string]string{
	"pppd-plugin": "loads a shared library as root",
	"pppd-call":   "runs an arbitrary pppd options file as root",
	"pppd-log":    "writes to an arbitrary path as root",
}

// RenderConfig builds the openfortivpn config den installs for a VPN entry. The
// contents of spec.ConfigFile are copied in rather than referenced, because that
// path is user-writable and would otherwise be re-read, as root, on every connect.
func RenderConfig(spec *config.VPNSpec) (string, error) {
	settings := newSettings()

	if spec.ConfigFile != "" {
		data, err := os.ReadFile(spec.ConfigFilePath())
		if err != nil {
			return "", fmt.Errorf("read config_file: %w", err)
		}
		if err := settings.addINI(string(data)); err != nil {
			return "", fmt.Errorf("%s: %w", spec.ConfigFile, err)
		}
	}

	// A gateway given alongside a config file wins, matching how den passes it
	// on the command line today.
	if spec.Gateway != "" {
		host, port := splitGateway(spec.Gateway)
		settings.set("host", host)
		if port != "" {
			settings.set("port", port)
		}
	}
	if err := settings.addArgs(spec.ExtraArgs); err != nil {
		return "", err
	}

	if settings.get("host") == "" {
		return "", fmt.Errorf("no gateway: set gateway, or host in the config file")
	}
	if settings.get("port") == "" {
		settings.set("port", "443")
	}
	// den has always connected with --saml-login; keep that when the source
	// config does not pick a callback port itself.
	if settings.get("saml-login") == "" {
		settings.set("saml-login", "8020")
	}

	var b strings.Builder
	b.WriteString("# Generated by `den vpn install-helper` — edit den.yaml and re-run.\n")
	b.WriteString("# Root-owned on purpose: den runs openfortivpn with this file without\n")
	b.WriteString("# asking for a password, so nothing user-writable may feed into it.\n")
	for _, k := range settings.keys {
		fmt.Fprintf(&b, "%s = %s\n", k, settings.values[k])
	}
	return b.String(), nil
}

// settings is an ordered key/value set: openfortivpn config files are read
// top-to-bottom, and a stable order keeps installs diffable.
type settings struct {
	keys   []string
	values map[string]string
}

func newSettings() *settings { return &settings{values: map[string]string{}} }

func (s *settings) get(k string) string { return s.values[k] }

func (s *settings) set(k, v string) {
	if _, seen := s.values[k]; !seen {
		s.keys = append(s.keys, k)
	}
	s.values[k] = v
}

func (s *settings) setChecked(k, v, source string) error {
	if why, bad := forbiddenKeys[k]; bad {
		return fmt.Errorf("%s sets %s, which %s — remove it before using the passwordless helper", source, k, why)
	}
	s.set(k, v)
	return nil
}

// addINI merges an openfortivpn config file.
func (s *settings) addINI(data string) error {
	for line := range strings.SplitSeq(data, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			return fmt.Errorf("cannot parse line %q", line)
		}
		if err := s.setChecked(strings.TrimSpace(k), strings.TrimSpace(v), "config_file"); err != nil {
			return err
		}
	}
	return nil
}

// addArgs merges extra_args, whose long options map one-to-one onto config keys.
func (s *settings) addArgs(args []string) error {
	for i := 0; i < len(args); i++ {
		arg := args[i]
		if !strings.HasPrefix(arg, "--") {
			return fmt.Errorf("extra_args: %q is not a long option; the helper only understands --key=value form", arg)
		}
		key, value, hasValue := strings.Cut(strings.TrimPrefix(arg, "--"), "=")

		// The negative spellings have no config key of their own.
		switch key {
		case "no-dns":
			key, value, hasValue = "set-dns", "0", true
		case "pppd-no-peerdns":
			key, value, hasValue = "pppd-use-peerdns", "0", true
		}
		if !hasValue {
			// `--trusted-cert abc` — take the next argument when it is not itself a flag.
			if i+1 < len(args) && !strings.HasPrefix(args[i+1], "--") {
				value = args[i+1]
				i++
			} else {
				value = "1"
			}
		}
		if err := s.setChecked(key, value, "extra_args"); err != nil {
			return err
		}
	}
	return nil
}

// splitGateway splits "host" or "host:port".
func splitGateway(gateway string) (host, port string) {
	if h, p, ok := strings.Cut(gateway, ":"); ok {
		return h, p
	}
	return gateway, ""
}

// SudoersFile renders the sudoers drop-in. Every command is pinned in full, so
// the rule grants exactly the four calls den makes for the installed profiles —
// not the wrapper with arbitrary arguments.
func SudoersFile(user string, slugs []string) string {
	var b strings.Builder
	b.WriteString("# Installed by `den vpn install-helper`; remove with `den vpn uninstall-helper`.\n")
	b.WriteString("#\n")
	b.WriteString("# Lets den bring the VPN up and down without an admin prompt. The helper\n")
	b.WriteString("# accepts only these profile names and runs openfortivpn with a root-owned\n")
	b.WriteString("# config, so these rules cannot be used to pass it other options.\n")
	fmt.Fprintf(&b, "%s ALL=(root) NOPASSWD: %s check\n", user, HelperPath)
	for _, slug := range slugs {
		for _, action := range []string{"start", "stop", "status"} {
			fmt.Fprintf(&b, "%s ALL=(root) NOPASSWD: %s %s %s\n", user, HelperPath, action, slug)
		}
	}
	return b.String()
}

// Script renders the wrapper. openfortivpnPath is baked in at install time.
func Script(openfortivpnPath string) string {
	return strings.NewReplacer(
		"@OPENFORTIVPN@", openfortivpnPath,
		"@PREFIX@", HelperPrefix,
		"@KILL_HUNG@", killHung("-x openfortivpn"),
		"@REAP_PPPD@", reapOrphanedPPPD,
	).Replace(helperScript)
}

// OutdatedScriptFix is what den says wherever it finds an outdated helper.
const OutdatedScriptFix = "re-run: den vpn install-helper (its stop cannot clear a hung openfortivpn or pppd)"

// ScriptOutdated reports whether installed, the text of an installed wrapper,
// differs from the one this den would install. The protocol line does not
// change when the script does, so an older wrapper keeps working — and keeps
// its older stop — until someone tells the user to reinstall it.
func ScriptOutdated(installed string) bool {
	for line := range strings.SplitSeq(installed, "\n") {
		if path, ok := strings.CutPrefix(line, "OPENFORTIVPN='"); ok {
			path, ok = strings.CutSuffix(path, "'")
			return !ok || Script(path) != installed
		}
	}
	return true
}

// InstalledScriptOutdated reads the installed wrapper (0755, so the user can)
// and reports whether it is outdated. The error is os.ReadFile's: one wrapping
// fs.ErrNotExist means the helper is not installed.
func InstalledScriptOutdated() (bool, error) {
	data, err := os.ReadFile(HelperPath)
	if err != nil {
		return false, err
	}
	return ScriptOutdated(string(data)), nil
}

const helperScript = `#!/bin/sh
# den VPN privilege helper — installed by ` + "`den vpn install-helper`" + `.
#
# Granted passwordless sudo for the exact commands in /etc/sudoers.d/den-vpn.
# It takes a profile name and nothing else: openfortivpn options can load code
# as root (--pppd-plugin) or write to any file (--pppd-log), so every parameter
# comes from the root-owned config rendered at install time, never from the
# caller.
set -eu

PREFIX=@PREFIX@
OPENFORTIVPN='@OPENFORTIVPN@'
PROTOCOL='` + helperProtocol + `'

usage() {
	echo "usage: den-vpn check | start <profile> | stop <profile> | status <profile>" >&2
	exit 2
}

need_root() {
	[ "$(id -u)" = "0" ] || { echo "den-vpn: must be run as root (via sudo)" >&2; exit 5; }
}

# resolve accepts only the slug shape den installs, so nothing can point the
# helper outside $PREFIX.
resolve() {
	case "$1" in
		"" | *[!a-z0-9-]* ) echo "den-vpn: invalid profile name" >&2; exit 2 ;;
	esac
	CONF="$PREFIX/etc/$1.conf"
	LOG="$PREFIX/var/log/$1.log"
	PIDFILE="$PREFIX/var/run/$1.pid"
	[ -f "$CONF" ] || { echo "den-vpn: unknown profile '$1' — re-run: den vpn install-helper" >&2; exit 3; }
}

# running_pid prints the live openfortivpn pid for this profile, if any. The
# command line has to name this profile's own config: pids get reused, and a
# second profile's tunnel is not this one.
running_pid() {
	[ -f "$PIDFILE" ] || return 1
	pid=$(cat "$PIDFILE" 2>/dev/null) || return 1
	case "$pid" in "" | *[!0-9]* ) return 1 ;; esac
	args=$(ps -o args= -p "$pid" 2>/dev/null) || return 1
	case "$args" in *openfortivpn*" -c $CONF"* ) echo "$pid"; return 0 ;; esac
	return 1
}

cmd_start() {
	need_root
	if pid=$(running_pid); then
		echo "den-vpn: already running (pid $pid)"
		return 0
	fi
	[ -x "$OPENFORTIVPN" ] || { echo "den-vpn: $OPENFORTIVPN not found — reinstall openfortivpn, then re-run: den vpn install-helper" >&2; exit 4; }

	# den tails this log as the invoking user to pick up the SAML URL, so hand
	# it over. The directory stays root-owned, so it cannot be swapped for a
	# symlink between truncation and the first write.
	: > "$LOG"
	chmod 600 "$LOG"
	if [ -n "${SUDO_UID:-}" ]; then
		chown "$SUDO_UID:${SUDO_GID:-0}" "$LOG" 2>/dev/null || true
	fi

	# Detached, so the tunnel outlives den itself — quitting the TUI has never
	# dropped the VPN and should not start now.
	nohup "$OPENFORTIVPN" -c "$CONF" </dev/null >>"$LOG" 2>&1 &
	echo $! > "$PIDFILE"
	chmod 644 "$PIDFILE"
	echo "den-vpn: started openfortivpn (pid $(cat "$PIDFILE"))"
}

cmd_stop() {
	need_root
	stopped=0
	if pid=$(running_pid); then
		kill -TERM "$pid" 2>/dev/null || true
		i=0
		while [ "$i" -lt 50 ]; do
			running_pid >/dev/null 2>&1 || break
			sleep 0.1
			i=$((i + 1))
		done
		if running_pid >/dev/null 2>&1; then
			kill -KILL "$pid" 2>/dev/null || true
		fi
		stopped=1
	fi
	rm -f "$PIDFILE"

	# Always sweep, even when the pidfile kill above succeeded. Sessions den lost
	# track of — one left behind by a dropped tunnel, or started before the helper
	# was installed — are reparented to init and survive every later stop. They are
	# invisible locally but each one holds a session on the gateway, and once
	# enough pile up the gateway refuses new SAML logins outright. Killing only the
	# pid we happen to know about is how they accumulated in the first place.
	if pkill -TERM -f "openfortivpn -c $CONF" 2>/dev/null; then
		stopped=1
	fi
	if pkill -TERM -x openfortivpn 2>/dev/null; then
		stopped=1
	fi

	# openfortivpn logs out of the gateway on TERM, and over a dead connection
	# that logout never returns. Printing "stopped" once the signal was sent is
	# how one such process outlived its stop and had a second one started on
	# top of it, so whatever is still running after 5 s is KILLed.
	@KILL_HUNG@

	# openfortivpn normally stops its own pppd child. When it is killed instead of
	# shutting down cleanly, pppd reparents to init and keeps its ppp interface up,
	# still holding a VPN-assigned address. Those never go away on their own, and
	# TERM does not always end one either: pppd answers it with an LCP terminate
	# over a link that is gone, so whatever outlives 5 s is KILLed.
	#
	# Matched narrowly — openfortivpn's fixed ppp peer address, and a parent of
	# init — so a pppd under a running openfortivpn, or another VPN's, is untouched.
	sleep 1
	@REAP_PPPD@
	if [ -n "$orphans" ]; then
		stopped=1
	fi

	# den logs a failing stop, and refuses to start a tunnel over one still
	# running; a "stopped" here would hide both. A pppd left over counts as
	# much as openfortivpn: it holds ppp0 and the DNS just the same.
	left=$(pgrep -x openfortivpn 2>/dev/null | tr '\n' ' ')
	if [ -n "$left" ]; then
		echo "den-vpn: openfortivpn (pid ${left% }) did not stop" >&2
		exit 1
	fi
	for p in $orphans; do
		if kill -0 "$p" 2>/dev/null; then
			echo "den-vpn: pppd (pid $p) did not stop" >&2
			exit 1
		fi
	done

	if [ "$stopped" = "1" ]; then
		echo "den-vpn: stopped"
	else
		echo "den-vpn: nothing to stop"
	fi
}

cmd_status() {
	if pid=$(running_pid); then
		echo "running (pid $pid)"
	else
		echo "not running"
	fi
}

[ "$#" -ge 1 ] || usage
action=$1
case "$action" in
	check ) echo "$PROTOCOL"; exit 0 ;;
	start | stop | status ) [ "$#" -eq 2 ] || usage; resolve "$2" ;;
	* ) usage ;;
esac

case "$action" in
	start ) cmd_start ;;
	stop ) cmd_stop ;;
	status ) cmd_status ;;
esac
`

// Available reports whether den can drive the VPN without a password prompt,
// and why not when it cannot. It never blocks on a prompt: `sudo -n` fails
// immediately when the rule is missing.
func Available(ctx context.Context) (bool, string) {
	if issue := HelperTrustIssue(); issue != "" {
		return false, issue
	}
	out, err := exec.CommandContext(ctx, "sudo", "-n", HelperPath, "check").Output()
	if err != nil {
		return false, "passwordless sudo rule is not active — run: den vpn install-helper"
	}
	if got := strings.TrimSpace(string(out)); got != helperProtocol {
		return false, fmt.Sprintf("helper reports %q, den expects %q — run: den vpn install-helper", got, helperProtocol)
	}
	return true, ""
}

// HelperTrustIssue returns "" when the installed wrapper is safe to run as
// root, or the reason it is not. A wrapper that the user (or anything running
// as them) can rewrite would turn the sudoers rule into passwordless root, so
// den falls back to the admin prompt instead of trusting it. The directories
// above it are checked too: being able to swap a parent directory is as good
// as being able to edit the file.
func HelperTrustIssue() string {
	if _, err := os.Stat(HelperPath); err != nil {
		if os.IsNotExist(err) {
			return "helper is not installed — run: den vpn install-helper"
		}
		return fmt.Sprintf("cannot stat %s: %v", HelperPath, err)
	}
	for path := HelperPath; path != "/" && path != "."; path = filepath.Dir(path) {
		fi, err := os.Lstat(path)
		if err != nil {
			return fmt.Sprintf("cannot stat %s: %v", path, err)
		}
		uid, ok := fileOwnerUID(fi)
		if !ok {
			return fmt.Sprintf("cannot determine the owner of %s on this platform", path)
		}
		if issue := trustIssue(path, uid, fi.Mode()); issue != "" {
			return issue
		}
	}
	return ""
}

// trustIssue names the reason a path must not be trusted with passwordless
// root: anyone other than root can replace it.
func trustIssue(path string, uid uint32, mode fs.FileMode) string {
	if mode&fs.ModeSymlink != 0 {
		return fmt.Sprintf("%s is a symlink; den only trusts a real root-owned file", path)
	}
	if uid != 0 {
		return fmt.Sprintf("%s is not owned by root", path)
	}
	if mode.Perm()&0o022 != 0 {
		return fmt.Sprintf("%s is writable by group or others", path)
	}
	return ""
}
