package discover

import (
	"fmt"
	"strconv"
	"strings"
	"time"

	"github.com/lukaszgard/den/internal/config"
)

// GenerateOptions says whose account the inventory came from and which bastion
// the services go through.
type GenerateOptions struct {
	Profile   string // AWS profile the tunnels and credentials use
	Region    string // AWS region code
	EnvName   string // key of the generated environment
	Bastion   Bastion
	FirstPort int // first local port handed out (default 50100)
	Generated time.Time
}

// Generate writes a starter den.yaml for inv. Every service references one
// environment, so moving to another bastion or profile is a one-place edit. A
// resource den cannot authenticate to yet (IAM auth off) is written commented
// out with the reason, rather than left out silently.
func Generate(inv Inventory, o GenerateOptions) string {
	if o.FirstPort == 0 {
		o.FirstPort = 50100
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	w("# yaml-language-server: $schema=den.schema.json")
	w("# Generated by `den init` on %s from AWS profile %q in %s.", o.Generated.Format("2006-01-02"), o.Profile, o.Region)
	w("# Review it before use: service names come from AWS identifiers, and den")
	w("# cannot know which database user you connect as. `den doctor` checks the rest.")
	w(`version: "1"`)
	w("")
	w("environments:")
	w("  %s:", yamlKey(o.EnvName))
	w("    region: %s", q(o.Region))
	w("    environment: %s", q(o.EnvName))
	if o.Bastion.Name != "" {
		w("    ec2_instance_id: %s   # %s", q(o.Bastion.InstanceID), o.Bastion.Name)
	} else {
		w("    ec2_instance_id: %s", q(o.Bastion.InstanceID))
	}
	w("    aws_profile: %s       # opens the SSM tunnel", q(o.Profile))
	w("    credential_profile: %s   # mints the IAM credential", q(o.Profile))
	w("    aws_region_code: %s", q(o.Region))
	w("")
	if len(inv.Resources) == 0 {
		w("services: []   # nothing den can reach was found in %s", o.Region)
		return b.String()
	}
	w("services:")
	port := o.FirstPort
	for _, r := range inv.Resources {
		lines := serviceLines(r, o.EnvName, port)
		port++
		prefix := ""
		if !r.IAMAuth {
			w("  # %s: IAM database authentication is off, so den cannot mint a token for it.", r.Name)
			w("  # Enable it on the %s, then uncomment:", r.Type)
			prefix = "# "
		}
		for _, n := range r.Notes {
			w("  # note: %s", n)
		}
		for _, l := range lines {
			w("  %s%s", prefix, l)
		}
		w("")
	}
	return b.String()
}

// serviceLines is one service entry, indented relative to the list.
func serviceLines(r Resource, env string, port int) []string {
	lines := []string{
		"- name: " + q(r.Name),
		"  type: " + string(r.Type),
		"  env: " + yamlKey(env),
		"  " + string(r.Type) + ":",
	}
	add := func(k string, v any) {
		switch v := v.(type) {
		case string:
			if v != "" {
				lines = append(lines, "    "+k+": "+q(v))
			}
		case int:
			lines = append(lines, "    "+k+": "+strconv.Itoa(v))
		case bool:
			if v {
				lines = append(lines, "    "+k+": true")
			}
		}
	}
	add("local_port", port)
	switch r.Type {
	case config.ServiceTypeRDS:
		add("rds_host", r.Host)
		if r.Engine == config.RDSEngineMySQL {
			add("engine", r.Engine)
			lines = append(lines, `    db_user: "CHANGE_ME"   # a database user granted IAM auth`)
		} else {
			lines = append(lines, `    db_user: "CHANGE_ME"   # the database user granted rds_iam`)
			add("update_pgpass", true)
		}
		add("db_name", r.DBName)
	case config.ServiceTypeRedis:
		add("redis_host", r.Host)
		add("memorydb", r.MemoryDB)
		add("serverless", r.Serverless)
		lines = append(lines,
			"    # For IAM auth, name the cache and your cache user:",
			"    # cache_name: "+q(r.CacheName),
			"    # user_id: your_cache_user")
	case config.ServiceTypeDocumentDB:
		add("documentdb_host", r.Host)
		add("db_name", r.DBName)
	case config.ServiceTypeRedshift:
		add("redshift_host", r.Host)
		add("cluster_identifier", r.ClusterIdentifier)
		add("workgroup_name", r.WorkgroupName)
		if r.DBName != "" && r.DBName != "dev" {
			add("db_name", r.DBName)
		}
	case config.ServiceTypeOpenSearch:
		add("opensearch_host", r.Host)
		add("serverless", r.Serverless)
	case config.ServiceTypeNeptune:
		add("neptune_host", r.Host)
		if r.Port != 0 && r.Port != 8182 {
			add("port", r.Port)
		}
	}
	return lines
}

// q quotes a YAML scalar. Go's double-quoted form is valid YAML for the
// identifiers and host names written here.
func q(s string) string { return strconv.Quote(s) }

// yamlKey writes a map key or bare reference, quoting only when needed.
func yamlKey(s string) string {
	for _, r := range s {
		plain := r == '-' || r == '_' || r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z'
		if !plain {
			return q(s)
		}
	}
	return s
}
