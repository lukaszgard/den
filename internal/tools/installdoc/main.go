// Command installdoc writes docs/doctor/install.md, the install reference for
// every tool den runs, from the prereq catalog that den doctor itself uses.
// Run it through `go generate` (see internal/prereq/catalog.go) or
// `make generate`; CI fails when the file is stale.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/lukaszgard/den/internal/platform"
	"github.com/lukaszgard/den/internal/prereq"
)

func main() {
	out := flag.String("o", "docs/doctor/install.md", "output file")
	flag.Parse()
	if err := os.WriteFile(*out, render(), 0o644); err != nil { //nolint:gosec // documentation is meant to be read
		fmt.Fprintln(os.Stderr, "installdoc:", err)
		os.Exit(1)
	}
}

// The platforms documented, each with its usual package manager. Downloads
// are shown for amd64; `den doctor --os <name>/arm64` prints the others.
var platforms = []struct{ name, label string }{
	{"macos/amd64", "macOS"},
	{"debian/amd64", "Debian / Ubuntu"},
	{"fedora/amd64", "Fedora / RHEL"},
	{"windows/amd64", "Windows"},
}

func render() []byte {
	var b bytes.Buffer
	b.WriteString(`<!-- Generated by internal/tools/installdoc from internal/prereq; do not edit. Run: make generate -->

# Installing what den needs

den runs a few programs it does not ship with: the AWS CLI and its Session
Manager plugin for tunnels, a client per data store for the connect commands,
and the CLIs behind secrets and the VPN. You only need the ones your den.yaml
uses. On your own machine, let den work it out:

` + "```bash" + `
den doctor                          # checks everything den.yaml uses
den check-install --for sops,rds    # only these features, config or not
den doctor --for sops --os windows  # another platform's steps, for onboarding notes
` + "```" + `

den prints install commands; it never runs them. The commands below are the
same ones den doctor prints. Download URLs are shown for amd64 (x86_64);
` + "`den doctor --os debian/arm64`" + ` prints the arm64 ones.

## Features

` + "`den doctor --for`" + ` takes these names. Tunnelled services assume the ` + "`ssm`" + `
transport unless ` + "`ssh`" + `, ` + "`eice`" + ` or ` + "`kubectl`" + ` is named too.

| Feature | For | Tools |
|---|---|---|
`)
	names := make([]string, 0, len(prereq.Features))
	for n := range prereq.Features {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		f := prereq.Features[n]
		tools := strings.Join(f.Tools, ", ")
		if f.Tunnelled {
			tools += " + a transport"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", n, f.About, tools)
	}

	b.WriteString("\n## Tools\n")
	for _, t := range prereq.Catalog {
		fmt.Fprintf(&b, "\n### %s\n\nUsed for %s.", t.ID, t.Purpose)
		if t.MinVersion != "" {
			fmt.Fprintf(&b, " Needs %s or newer: %s.", t.MinVersion, strings.TrimSuffix(t.MinReason, "."))
		}
		fmt.Fprintf(&b, " Docs: <%s>\n", t.Docs)
		for _, p := range platforms {
			info, err := platform.ForOS(p.name)
			if err != nil {
				panic(err)
			}
			st := prereq.Check(context.Background(), t, prereq.PreviewEnv(info))
			fmt.Fprintf(&b, "\n**%s**", p.label)
			switch {
			case st.Unsupported != "":
				fmt.Fprintf(&b, ": not available. %s.\n", st.Unsupported)
				continue
			case len(st.Install) == 0:
				fmt.Fprintf(&b, ": see the docs.\n")
				continue
			}
			fmt.Fprintf(&b, " (%s)\n\n```sh\n%s\n```\n", prereq.ManagerName(st.Via), strings.Join(st.Install, "\n"))
			if len(st.Upgrade) > 0 {
				fmt.Fprintf(&b, "\nIf %s installs one older than %s:\n\n```sh\n%s\n```\n",
					prereq.ManagerName(st.Via), t.MinVersion, strings.Join(st.Upgrade, "\n"))
			}
		}
	}
	return b.Bytes()
}
