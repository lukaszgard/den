// updateCLIDoc rewrites docs/cli/README.md: `make generate` runs this test with it.
var updateCLIDoc = flag.Bool("update", false, "rewrite docs/cli/README.md from the command tree")

const cliReference = "../../docs/cli/README.md"

// cliGuides links a command (and the ones under it, unless they have a guide of
// their own: the longest prefix wins) to the page that explains its feature,
// as GitHub and the site read it from docs/cli/.
var cliGuides = map[string]string{
	"den doctor":         "../doctor/README.md",
	"den init":           "../init/README.md",
	"den mcp":            "../mcp/README.md",
	"den run":            "../runbooks/README.md",
	"den runbook":        "../runbooks/README.md",
	"den runbook new":    "../runbooks/agents/cli/README.md",
	"den runbook source": "../runbook-sources/README.md",
	"den schema":         "../schema/README.md",
	"den vpn":            "../vpn/README.md",
	"den create-env":     "../docker/README.md",
	"den update":         "../updates/README.md",
}

// TestCLIReference keeps docs/cli/README.md what the command tree says. It is
// generated from newRootCmd, so the shipped binary needs no doc command and no
// doc library: run `make generate` after changing a command, a flag or its help.
func TestCLIReference(t *testing.T) {
	var b bytes.Buffer
	b.WriteString(`<!-- Generated by cmd/den/clidoc_test.go from the command tree; do not edit. Run: make generate -->

# Command-line reference

Every ` + "`den`" + ` command and its flags, generated from the commands themselves, so it
matches ` + "`den --help`" + ` of this version. Run with no command, ` + "`den`" + ` opens the dashboard;
` + "`den --version`" + ` prints the version and ` + "`den COMMAND --help`" + ` the text below.

Without ` + "`-c`" + ` den reads ` + "`./den.yaml`" + `, then ` + "`~/.config/den/den.yaml`" + `; with it, the file must
exist. The keys of the file are in the [configuration reference](../config/README.md).

`)
	root := newRootCmd()
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		if c.Hidden {
			return
		}
		writeCommand(t, &b, c)
		for _, sub := range c.Commands() {
			walk(sub)
		}
	}
	walk(root)
	got := b.Bytes()

	if *updateCLIDoc {
		if err := os.WriteFile(cliReference, got, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(cliReference)
	if err != nil {
		t.Fatalf("%v: run make generate", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is out of date with the commands: run make generate", filepath.Clean(cliReference))
	}
}

// writeCommand writes one command: what it is for, how to call it, its flags.
func writeCommand(t *testing.T, b *bytes.Buffer, c *cobra.Command) {
	t.Helper()
	fmt.Fprintf(b, "## `%s`\n\n%s\n\n", c.CommandPath(), c.Short)
	if c.Long != "" && c.Long != c.Short {
		b.WriteString(prose(c.Long))
	}
	fmt.Fprintf(b, "```text\n%s\n```\n\n", c.UseLine())
	if len(c.Aliases) > 0 {
		fmt.Fprintf(b, "Also called `%s`.\n\n", strings.Join(c.Aliases, "`, `"))
	}
	if g := cliGuide(c.CommandPath()); g != "" {
		if _, err := os.Stat(filepath.Join(filepath.Dir(cliReference), g)); err != nil {
			t.Fatalf("guide of %s: %v", c.CommandPath(), err)
		}
		fmt.Fprintf(b, "Guide: [docs/%s](%s)\n\n", strings.TrimSuffix(strings.TrimPrefix(g, "../"), "/README.md"), g)
	}
	if c.Example != "" {
		fmt.Fprintf(b, "Examples:\n\n```text\n%s\n```\n\n", dedent(c.Example))
	}
	if flags := c.LocalFlags().FlagUsages(); strings.TrimSpace(flags) != "" {
		fmt.Fprintf(b, "Flags:\n\n```text\n%s\n```\n\n", dedent(flags))
	}
}

// cliGuide is the page of the longest guide key that prefixes the command.
func cliGuide(path string) string {
	best := ""
	for k := range cliGuides {
		if (path == k || strings.HasPrefix(path, k+" ")) && len(k) > len(best) {
			best = k
		}
	}
	return cliGuides[best]
}

// prose turns a command's long help, written for a terminal, into Markdown:
// its paragraphs are re-flowed, its indented ones (an example, a command line)
// become code blocks, and a flag or a <placeholder> in running text is put in
// code so that neither becomes a dash or an HTML tag.
func prose(long string) string {
	var out strings.Builder
	for _, para := range strings.Split(strings.TrimSpace(long), "\n\n") {
		if strings.HasPrefix(para, " ") {
			fmt.Fprintf(&out, "```text\n%s\n```\n\n", dedent(para))
			continue
		}
		words := strings.Fields(para)
		inCode := false // inside a `span` the author already marked up
		for i, w := range words {
			if !inCode {
				words[i] = codeWord(w)
			}
			if strings.Count(w, "`")%2 == 1 {
				inCode = !inCode
			}
		}
		out.WriteString(strings.Join(words, " ") + "\n\n")
	}
	return out.String()
}

// codeWord puts a flag name or a <placeholder> in backticks, leaving the
// punctuation after it outside.
func codeWord(w string) string {
	if strings.Contains(w, "`") {
		return w
	}
	core := strings.TrimRight(w, ".,;:)")
	if strings.HasPrefix(core, "--") || strings.Contains(core, "<") {
		return "`" + core + "`" + w[len(core):]
	}
	return w
}

// dedent removes the indentation every line of s shares, and the line breaks
// around it.
func dedent(s string) string {
	lines := strings.Split(strings.Trim(s, "\n"), "\n")
	indent := -1
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			continue
		}
		if n := len(l) - len(strings.TrimLeft(l, " ")); indent < 0 || n < indent {
			indent = n
		}
	}
	for i, l := range lines {
		if len(l) >= indent && indent > 0 {
			lines[i] = strings.TrimRight(l[indent:], " ")
		} else {
			lines[i] = strings.TrimRight(l, " ")
		}
	}
	return strings.Join(lines, "\n")
}
